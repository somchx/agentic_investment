// Centralized query key factory so invalidation stays consistent across hooks.
export const queryKeys = {
  companies: ["companies"] as const,
  reasons: (ticker?: string) => (ticker ? (["reasons", ticker] as const) : (["reasons"] as const)),
  xbrlTags: (ticker: string) => ["xbrl-tags", ticker] as const,
  report: (ticker: string) => ["report", ticker] as const,
  aiSummary: (ticker: string) => ["ai-summary", ticker] as const,
  profiles: ["profiles"] as const,
  investorProfile: ["investor-profile"] as const,
  screen: (reasonKeys: string[]) => ["screen", ...[...reasonKeys].sort()] as const,
  positions: ["positions"] as const,
  portfolioSummary: ["portfolio", "summary"] as const,
  thesisReviews: (positionId: string) => ["thesis-reviews", positionId] as const,
  revalidation: (positionId: string) => ["revalidation", positionId] as const,
  thesisDebates: (positionId: string) => ["thesis-debates", positionId] as const,
  quote: (ticker: string) => ["quote", ticker] as const,
  quotes: (tickers: string[]) => ["quotes", ...[...tickers].sort()] as const,
  history: (ticker: string, range: string) => ["history", ticker, range] as const,
  me: ["auth", "me"] as const,
  notifications: ["notifications"] as const,
  notificationsUnreadCount: ["notifications", "unread-count"] as const,
  conversations: ["conversations"] as const,
  conversation: (id: number) => ["conversations", id] as const,
}
